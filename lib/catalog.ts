type Pair = readonly [string, string];

export interface Situation {
  id: string;
  route: Route;
  title: string;
  keywords: string[];
  tip: string;
  avoid: string;
  sensitive: boolean;
  responses: Record<Tone, Pair>;
}

function define(
  route: Route,
  id: string,
  title: string,
  keywords: string,
  tip: string,
  avoid: string,
  soft: Pair,
  sweet: Pair,
  direct: Pair,
  sensitive = false
): Situation {
  return {
    route,
    id,
    title,
    keywords: keywords.split(" "),
    tip,
    avoid,
    sensitive,
    responses: { soft, sweet, direct }
  };
}

